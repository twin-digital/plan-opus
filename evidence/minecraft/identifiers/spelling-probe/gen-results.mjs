// Builds RESULTS-CAPTURED.md mechanically from the captured logs, so no phase can be omitted by
// hand. Every [nsprobe] line of every phase goes in, grouped by phase, plus every non-scripting
// WARN/ERROR line and every Pack Stack line.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.dirname(fileURLToPath(import.meta.url));
const RAWS = ["RAW-OUTPUT.txt", "RAW-OUTPUT2.txt"].filter((f) => fs.existsSync(path.join(DIR, f)));

const out = [];
const w = (s = "") => out.push(s);

w("# Captured output — bedrock namespace-character probe");
w();
w("Generated by `node gen-results.mjs` from the raw server logs. Every phase that ran appears here.");
w();
w(`Raw logs: ${RAWS.join(", ")}`);
w();

let seenPhases = new Set();
for (const f of RAWS) {
  const raw = fs.readFileSync(path.join(DIR, f), "utf8").split("\n");
  w(`## ${f}`);
  w();
  const version = [...raw.join("\n").matchAll(/Version: ([\d.]+)/g)].map((m) => m[1]);
  w(`server version lines: ${[...new Set(version)].join(", ") || "(none in this slice)"}`);
  w();

  const phases = new Map();
  let current = "boot";
  for (const line of raw) {
    const m = line.match(/\[nsprobe\] ([a-z0-9-]+)(?:\/[^ ]*)? ::/);
    let key = m ? m[1] : line.includes("[nsprobe]") ? current : null;
    if (key === "arena" || key === "boot") key = current;
    else if (m) current = key;
    if (key === null) continue;
    if (!phases.has(key)) phases.set(key, []);
    phases.get(key).push(line.trimEnd());
  }
  for (const [phase, lines] of phases) {
    seenPhases.add(phase);
    w(`### phase: ${phase} (${lines.length} lines)`);
    w();
    w("```");
    for (const l of lines) w(l);
    w("```");
    w();
  }

  w("### non-scripting WARN/ERROR lines");
  w();
  w("```");
  for (const line of raw) {
    if (line.includes("[Scripting]")) continue;
    if (/WARN|ERROR/.test(line)) w(line.trimEnd());
  }
  w("```");
  w();
  w("### Pack Stack lines");
  w();
  w("```");
  for (const line of raw) if (line.includes("Pack Stack")) w(line.trimEnd());
  w("```");
  w();
}

w(`Phases captured: ${[...seenPhases].join(", ")}`);
fs.writeFileSync(path.join(DIR, "RESULTS-CAPTURED.md"), out.join("\n") + "\n");
console.log(`wrote RESULTS-CAPTURED.md, phases: ${[...seenPhases].join(", ")}`);
